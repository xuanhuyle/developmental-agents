class _Probe:
    """A deterministic stand-in for the Messages API (no network). It answers like a model that reads its MODE RULES:
    the root reads every document in one QUERY, or, if `divide` and SPAWN is allowed at any step, splits them over two
    children; children read the documents named in their objective. Only the request and event streams matter."""

    def __init__(self, divide: bool):
        self.divide = divide
        self.requests: list = []

    def create(self, **kw):
        import re
        from devagents.runtime.resources import estimate_tokens
        self.requests.append(json.loads(json.dumps(kw, default=vars)))
        system, first = kw["system"], kw["messages"][0]["content"]
        step = sum(1 for m in kw["messages"] if m["role"] == "assistant")
        if first.startswith("Task "):
            task = TASKS_BY_ID[re.match(r"Task (\w+)\.", first).group(1)]
            docs = list(task.routes[0].docs)
            if step == 0 and self.divide and "You may SPAWN at any step" in system:
                action = {"rationale": "split", "action": "SPAWN", "wait_for_children": True,
                          "children": [{"objective": f"Read {' '.join(h)} for: {task.question}", "context": "",
                                        "budget_usd": 0.2, "lifetime_s": 600} for h in (docs[0::2], docs[1::2])]}
            elif step == 0:
                action = {"rationale": "read", "action": "QUERY", "requests": [{"kind": "doc", "target": d} for d in docs]}
            else:
                action = {"rationale": "answer", "action": "TERMINATE", "answer": task.answer}
        else:
            named = re.findall(r"(?:region|supplier)-[a-z]+", first.split("Context from")[0])
            if step == 0 and named:
                action = {"rationale": "read", "action": "QUERY", "requests": [{"kind": "doc", "target": d} for d in named]}
            else:
                action = {"rationale": "report", "action": "TERMINATE", "answer": "the facts I found"}
        text = json.dumps(action)
        chars = len(system) + sum(len(m["content"]) if isinstance(m["content"], str)
                                  else sum(len(getattr(b, "text", "")) for b in m["content"]) for m in kw["messages"])
        return SimpleNamespace(content=[SimpleNamespace(type="text", text=text)], stop_reason="end_turn",
                               usage=SimpleNamespace(input_tokens=chars // 4 + 5, output_tokens=estimate_tokens(text) + 40,
                                                     cache_read_input_tokens=0, cache_creation_input_tokens=0))


def request_stream_sha(wrap, constants: Constants, task_ids=("X2", "T01", "T04", "T07", "T10")) -> str:
    """Run the probe through `wrap(LLMPolicy)` for single and developmental in every 0c cell; hash every API request
    (model, max_tokens, system, messages, output_config) and every event (minus wall-clock fields)."""
    from devagents.agents.policies import LLMPolicy
    info = InformationEnvironment(load_world(), constants.sources)
    streams = []
    for task_id in task_ids:
        for mode, divide in (("single", False), ("developmental", False), ("developmental", True)):
            probe = _Probe(divide)
            policy = wrap(LLMPolicy(constants.compute, client=SimpleNamespace(messages=probe)))
            run = Run(RunConfig(TASKS_BY_ID[task_id], constants.regimes["urgent"], mode, compute=constants.compute,
                                coord=constants.coord), policy, info)
            run.execute()
            events = [{k: v for k, v in e.items() if k not in ("wall", "wall_s")} for e in run.log.events]
            streams.append({"run": run.cfg.run_id, "divide": divide, "requests": probe.requests, "events": events})
    return hashlib.sha256(json.dumps(streams, sort_keys=True, default=str).encode()).hexdigest()


