def sha256_lf(path: Path) -> str:
    """sha256 of a committed text file with CRLF normalized to LF. Git for Windows checks text files out with CRLF by
    default (core.autocrlf), which would change a raw-byte hash although nothing changed; on an LF checkout this equals
    the raw-byte sha256."""
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def sha256_json(obj) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


