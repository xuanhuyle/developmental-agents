def write_prereg(path: Path = PREREG_PATH) -> str:
    prereg = {**build_prereg(), "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    path.parent.mkdir(parents=True, exist_ok=True)
    # No sort_keys: the scripted actions keep the oracle's key order, so the SPAWN the live root re-reads is the
    # oracle's serialization byte for byte. build_prereg is deterministic, so the file is too.
    path.write_text(json.dumps(prereg, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return sha256_lf(path)


