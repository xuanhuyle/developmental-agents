def git_commit() -> str:
    """Informational only (recorded per invocation, never compared): the checkout's commit, +dirty if tracked files
    differ from it."""
    try:
        def git(*args):
            return subprocess.run(["git", "--no-optional-locks", *args], cwd=ROOT, capture_output=True, check=True,
                                  encoding="utf-8", errors="replace").stdout.strip()
        return git("rev-parse", "HEAD") + ("+dirty" if git("status", "--porcelain", "--untracked-files=no") else "")
    except Exception:  # informational: never let it stop a run
        return "unknown"


