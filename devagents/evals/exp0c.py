# --------------------------------------------------------------------------- the scripted topology

def _parse_org(name: str) -> Org:
    head, route = name.split("@r")
    kind = head.rstrip("0123456789")
    return Org(kind, int(route), int(head[len(kind):]) if kind != "solo" else 0)


def derive_org(cell: str, frozen: dict, constants: Constants) -> tuple[Org, str]:
    """The cell's one-shot organization from pre-existing artefacts: the 0b freeze's `router_div` for calibrated
    cells; for the held-out pilot task, the unchanged calibration procedure (`calibrate`, base point) applied at the
    frozen 0b constants and assumptions, whose `router_div` rule is the same one that produced the frozen cells."""
    cells = frozen["calibration"]["cells"]
    if cell in cells:
        return _parse_org(cells[cell]["router_div"]), f"data/exp0b/frozen.json calibration.cells[{cell!r}].router_div"
    task_id, regime = cell.split("|")
    cal = calibrate(constants, frozen_assumptions(frozen), with_grid=False, tasks=[TASKS_BY_ID[task_id]])
    return (_parse_org(cal["cells"][cell]["router_div"]),
            "calibrate.label router_div at the frozen 0b constants and assumptions (base point), unchanged code")


def topology(cell: str, frozen: dict, constants: Constants) -> dict:
    """The pre-registered first SPAWN of scripted `central` in `cell`: the oracle's own SPAWN action, byte for byte."""
    org, source = derive_org(cell, frozen, constants)
    if org.k != PREDECLARED_K[cell]:
        raise SystemExit(f"{cell}: the derived one-shot organization {org.name} has k={org.k}, but k={PREDECLARED_K[cell]}"
                         " was pre-declared. STOP: the design is not changed to make this pass (SPEC_0C.md §5).")
    task = TASKS_BY_ID[cell.split("|")[0]]
    route = task.routes[org.route]
    if org.kind != "fanout" or route.sql:
        raise SystemExit(f"{cell}: {org.name} is not a document-only fan-out; its objectives could carry post-t0 "
                         "information. STOP.")
    script = oracle_script(task, route, org, 0)
    action = script(SimpleNamespace(parent=None, steps=0, id=ROOT_AGENT), None, ["SPAWN"])
    partition = [list(route.docs[i::org.k]) for i in range(org.k)]
    return {"cell": cell, "task": task.id, "org": org.name, "source": source, "k": org.k, "route": org.route,
            "partition": partition, "objectives": [c["objective"] for c in action["children"]],
            "contexts": [c["context"] for c in action["children"]], "action": action, "action_sha": sha256_json(action)}


def objective_template(task) -> str:
    return f"Find the facts needed for: {task.question} Read only the sources named in this objective: "


def t0_problems(topo: dict, info: InformationEnvironment) -> list[str]:
    """A scripted objective may contain only the task's question and catalog document ids, in the oracle template."""
    problems = []
    task = TASKS_BY_ID[topo["task"]]
    prefix = objective_template(task)
    texts = list(info.world.docs.values())
    for i, (objective, docs, context) in enumerate(zip(topo["objectives"], topo["partition"], topo["contexts"])):
        if objective != prefix + "; ".join(docs):
            problems.append(f"{topo['cell']} child {i + 1}: objective is not the oracle template over its documents")
        if context:
            problems.append(f"{topo['cell']} child {i + 1}: non-empty context")
        for d in docs:
            if d == SQL_SOURCE or d not in info.source_ids:
                problems.append(f"{topo['cell']} child {i + 1}: {d!r} is not a catalog document")
        rest = objective.replace(task.question, "")
        for d in docs:
            rest = rest.replace(d, "")
        skeleton = "Find the facts needed for:  Read only the sources named in this objective: " + "; " * (len(docs) - 1)
        if rest != skeleton:
            problems.append(f"{topo['cell']} child {i + 1}: objective carries text beyond the question and document ids")
        for answer in (task.answer, *task.aliases):
            if answer.casefold() in rest.casefold():
                problems.append(f"{topo['cell']} child {i + 1}: objective contains the answer")
        for text in texts:  # no line of any document's content appears in an objective
            for line in text.splitlines():
                if len(line.strip()) >= 25 and line.strip() in objective:
                    problems.append(f"{topo['cell']} child {i + 1}: objective contains document content")
    docs = task.routes[topo["route"]].docs
    if topo["partition"] != [list(docs[i::topo["k"]]) for i in range(topo["k"])]:
        problems.append(f"{topo['cell']}: partition is not docs[i::k] over the route's committed order")
    return problems


def scripted_policy(inner, prereg: dict) -> ScriptedFirstSpawnPolicy:
    """The policy every 0c run uses: the unchanged inner policy, with the pre-registered `central` first step."""
    actions = {t["task"]: t["action"] for t in prereg["scripted_central"].values()}
    pricing = prereg["scripted_step_pricing"]
    return ScriptedFirstSpawnPolicy(inner, actions, pricing["input_scale"], pricing["reasoning_tokens"])


