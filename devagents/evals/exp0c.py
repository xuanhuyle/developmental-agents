# --------------------------------------------------------------------------- offline (LLM-free) simulation

def _simulate(task, regime, mode: str, policy, constants: Constants, info) -> tuple[dict, list[dict]]:
    run = Run(RunConfig(task, regime, mode, compute=constants.compute, coord=constants.coord), policy, info)
    run.execute()
    return metrics_from_events(run.log.events), run.log.events


def _oracle(task, org: Org, asm: Assumptions) -> ScriptedPolicy:
    return ScriptedPolicy(oracle_script(task, task.routes[org.route], org, asm.extra_work_steps),
                          reasoning_tokens=asm.reasoning_tokens, input_scale=asm.input_scale)


def _fit(m: dict, regime) -> float | None:
    clean = m["quality"] == 1.0 and m["outcome"] == "answered" and not m["cap_hits"] and not m["invalid_actions"]
    return round(_fitness(m, regime), 4) if clean else None


def mechanics_problems(topo: dict, events: list[dict], constants: Constants, regime) -> list[str]:
    """In one offline scripted-central run: exact k, objectives, allocation, lifetime and spawn fees; caps respected."""
    problems = []
    k = topo["k"]
    spawned = [e for e in events if e["type"] == "AGENT_SPAWNED" and e["agent"] == ROOT_AGENT]
    if [e["objective"] for e in spawned] != topo["objectives"]:
        problems.append(f"{topo['cell']}: created objectives differ from the pre-registered ones")
    if len(spawned) != k:
        problems.append(f"{topo['cell']}: {len(spawned)} children instead of {k}")
    coord = constants.coord
    fees = [coord.spawn_fee + coord.transfer_per_token * e["context_tokens"] for e in spawned]
    if [e["fee"] for e in spawned] != fees:
        problems.append(f"{topo['cell']}: spawn fees differ from spawn_fee + transfer_per_token x tokens")
    first = next(e for e in events if e["type"] == "RESOURCE_CONSUMED" and e["kind"] == "llm" and e["agent"] == ROOT_AGENT)
    started = next(e for e in events if e["type"] == "ACTION_STARTED" and e["agent"] == ROOT_AGENT and e["step"] == 1)
    balance = usd(regime.budget_usd) - first["amount"]
    t_decided = started["t"] + started["llm_latency_s"]
    share, life = fixed_allocation(balance, sum(fees), k, round((regime.deadline_s - t_decided) * 1_000_000),
                                   0.5, 0.6)
    allocations = [e["amount"] for e in events if e["type"] == "RESOURCE_ALLOCATED" and e["kind"] == "allocation"]
    if allocations != [share] * k:
        problems.append(f"{topo['cell']}: allocations {allocations} differ from the fixed rule's {share}")
    created = [e for e in events if e["type"] == "AGENT_CREATED" and e["parent"] == ROOT_AGENT]
    t_spawned = started["t"] + started["llm_latency_s"] + started["action_latency_s"]
    expected_deadline = min(regime.deadline_s, t_spawned + life / 1_000_000)
    if any(abs(e["deadline"] - expected_deadline) > 1e-6 for e in created):
        problems.append(f"{topo['cell']}: child lifetimes differ from 60% of the remaining time")
    m = metrics_from_events(events)
    if m["agents"] > 16 or m["max_live_agents"] > constants.compute.max_concurrency:
        problems.append(f"{topo['cell']}: agent or concurrency cap exceeded")
    if m["cap_hits"] or m["invalid_actions"] or "budget_exhausted" in m["termination_reasons"]:
        problems.append(f"{topo['cell']}: cap hit, invalid action or exhausted budget")
    scripted = [e for e in events if e["type"] == "SCRIPTED_ACTION"]
    if len(scripted) != 1 or scripted[0]["action"] != topo["action"]:
        problems.append(f"{topo['cell']}: the scripted SPAWN is not logged exactly once")
    if not scripted or first["amount"] <= 0 or first["in_tokens"] != scripted[0]["in_tokens"]:
        problems.append(f"{topo['cell']}: the scripted step is not charged as an LLM step")
    return problems


def offline_geometry(frozen: dict, topologies: dict, constants: Constants) -> dict:
    """single, one-child central and scripted central per cell, at the frozen and at the live 0b token assumptions.
    The topology is fixed; nothing here chooses k. The scripted step is priced at the frozen assumptions in both."""
    info = InformationEnvironment(load_world(), constants.sources)
    base = frozen_assumptions(frozen)
    actions = {t["task"]: t["action"] for t in topologies.values()}
    out = {}
    for label, asm in (("frozen", base), ("live_0b", LIVE_0B_TOKENS)):
        rows, problems = {}, []
        for cell, topo in topologies.items():
            task, regime = TASKS_BY_ID[topo["task"]], constants.regimes[cell.split("|")[1]]
            org = _parse_org(topo["org"])
            single, _ = _simulate(task, regime, "single", _oracle(task, Org("solo", org.route), asm), constants, info)
            one, _ = _simulate(task, regime, "central", _oracle(task, Org("fanout", org.route, 1), asm), constants, info)
            policy = ScriptedFirstSpawnPolicy(_oracle(task, org, asm), actions, base.input_scale, base.reasoning_tokens)
            scripted, events = _simulate(task, regime, "central", policy, constants, info)
            plain, _ = _simulate(task, regime, "central", _oracle(task, org, asm), constants, info)
            problems += mechanics_problems(topo, events, constants, regime)
            rows[cell] = {"single": _fit(single, regime), "central_one_child": _fit(one, regime),
                          "scripted_central": _fit(scripted, regime), "oracle_fanout_central": _fit(plain, regime),
                          "scripted_parallel": scripted["parallel"], "scripted_agents": scripted["agents"],
                          "scripted_llm_calls": scripted["llm_calls"]}
        keys = ("single", "central_one_child", "scripted_central")
        unclean = [f"{label} {c}: an offline run did not finish cleanly" for c, r in rows.items()
                   if any(r[k] is None for k in keys + ("oracle_fanout_central",))]
        stage1 = [rows[c] for c in STAGE1.cells]
        means = {k: (round(statistics.fmean(r[k] for r in stage1), 4) if not unclean else None) for k in keys}
        out[label] = {"assumptions": asdict(asm), "cells": rows, "stage1_means": means,
                      "ordering_holds": not unclean and all(r["scripted_central"] > r["single"] > r["central_one_child"]
                                                            for r in rows.values()),
                      "mechanics_problems": problems + unclean}
    return out


